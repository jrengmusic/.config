        return found
      end,
      cwd = '${workspaceFolder}',
      stopOnEntry = false,
      args = {},

    },
    {
      name = 'Attach to DAW (VST3)',
      type = plugin_adapter,
      -- Windows: launch DAW through debugger (owns process from birth, tracks all DLL loads)
      -- Mac: attach to already-running DAW
